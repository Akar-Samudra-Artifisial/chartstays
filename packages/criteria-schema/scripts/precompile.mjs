// Compile the criteria schema ahead of time (Ajv standalone code) into dist/precompiled.js, so a
// browser page can validate criteria under a Content Security Policy without 'unsafe-eval'
// (Ajv's run-time compile uses new Function). Run after tsc; dist/validate.js must exist.
import { readFile, writeFile } from "node:fs/promises";
import { Ajv } from "ajv";
import standaloneModule from "ajv/dist/standalone/index.js";

const standaloneCode = standaloneModule.default ?? standaloneModule;
const PKG = new URL("../", import.meta.url);

// The one Ajv run-time helper the schema needs (maxLength/minLength), inlined so the output
// is a plain ES module without require(). Same algorithm as ajv/dist/runtime/ucs2length.
const UCS2LENGTH = `function __ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length++;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      const next = str.charCodeAt(pos);
      if ((next & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}
`;

const schema = JSON.parse(await readFile(new URL("schema/criteria.schema.json", PKG), "utf8"));
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
let code = standaloneCode(ajv, ajv.compile(schema));
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', "__ucs2length");
if (/\brequire\(/.test(code)) throw new Error(`precompile: unexpected require() in the standalone validator: ${code.match(/require\([^)]*\)/)[0]}`);
// "use strict" must stay first; the helper follows it.
code = code.replace(/^"use strict";/, `"use strict";\n${UCS2LENGTH}`);

const header = "// GENERATED by scripts/precompile.mjs from schema/criteria.schema.json. Do not edit.\n";
await writeFile(new URL("dist/criteria-check.js", PKG), header + code);
await writeFile(
  new URL("dist/precompiled.js", PKG),
  `${header}import check from "./criteria-check.js";\nimport { criteriaValidatorFrom } from "./validate.js";\n\n/** Criteria validator compiled ahead of time: no eval at run time. */\nexport const validateCriteriaPrecompiled = criteriaValidatorFrom(check);\n`,
);
await writeFile(
  new URL("dist/precompiled.d.ts", PKG),
  `${header}import type { ValidationResult } from "./validate.js";\n\n/** Criteria validator compiled ahead of time: no eval at run time. */\nexport declare const validateCriteriaPrecompiled: (doc: unknown) => ValidationResult;\n`,
);
console.log("precompile: wrote dist/precompiled.js");
